"""Plugin secret management.

Rules:
- Secrets may be generated by USR or imported by an operator.
- Raw values are exposed only at creation/rotation time via explicit APIs.
- The runtime persists secret material so callback registration and
  restart-safe verification can resume after process restarts.
- Outbound/inbound HMAC operations use the raw secret value.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import logging
import os
import secrets
from collections.abc import Iterable
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import TYPE_CHECKING, Any

from ultima_scraper_db_archive.crypto import (
    decrypt_secret_value,
    encrypt_secret_value,
    is_encrypted_secret,
)

logger = logging.getLogger(__name__)

if TYPE_CHECKING:
    from .repository import PluginRepository

DEFAULT_GRACE_PERIOD = timedelta(minutes=15)
SECRET_BYTE_LENGTH = 32


def _generate_secret() -> str:
    return secrets.token_urlsafe(SECRET_BYTE_LENGTH)


def _hash_secret(raw: str) -> str:
    return hashlib.sha256(raw.encode()).hexdigest()


class PluginSecret:
    """A single secret entry for one endpoint / target."""

    __slots__ = (
        "plugin_id",
        "scope_kind",
        "scope_name",
        "active_secret_value",
        "active_secret_hash",
        "previous_secret_value",
        "previous_secret_hash",
        "grace_deadline",
        "created_at",
        "rotated_at",
    )

    def __init__(
        self,
        plugin_id: str,
        scope_kind: str,
        scope_name: str,
        active_secret_value: str,
        *,
        created_at: datetime | None = None,
    ) -> None:
        self.plugin_id = plugin_id
        self.scope_kind = scope_kind
        self.scope_name = scope_name
        self.active_secret_value = active_secret_value
        self.active_secret_hash = _hash_secret(active_secret_value)
        self.previous_secret_value: str | None = None
        self.previous_secret_hash: str | None = None
        self.grace_deadline: datetime | None = None
        self.created_at = created_at or datetime.now(UTC)
        self.rotated_at: datetime | None = None

    def _grace_active(self) -> bool:
        return (
            self.previous_secret_hash is not None
            and self.previous_secret_value is not None
            and self.grace_deadline is not None
            and datetime.now(UTC) < self.grace_deadline
        )

    def verify(self, raw_candidate: str) -> bool:
        """Return True if *raw_candidate* matches the active or grace secret."""
        candidate_hash = _hash_secret(raw_candidate)
        if hmac.compare_digest(self.active_secret_hash, candidate_hash):
            return True
        if self._grace_active():
            assert self.previous_secret_hash is not None
            return hmac.compare_digest(self.previous_secret_hash, candidate_hash)
        return False

    def sign_payload(self, payload: bytes) -> str:
        return hmac.new(
            self.active_secret_value.encode(),
            payload,
            hashlib.sha256,
        ).hexdigest()

    def verify_signature(self, payload: bytes, signature: str) -> bool:
        normalized = signature.strip()
        if normalized.startswith("sha256="):
            normalized = normalized.split("=", 1)[1]

        active_sig = hmac.new(
            self.active_secret_value.encode(),
            payload,
            hashlib.sha256,
        ).hexdigest()
        if hmac.compare_digest(active_sig, normalized):
            return True

        if self._grace_active():
            assert self.previous_secret_value is not None
            previous_sig = hmac.new(
                self.previous_secret_value.encode(),
                payload,
                hashlib.sha256,
            ).hexdigest()
            return hmac.compare_digest(previous_sig, normalized)
        return False

    def to_dict(self) -> dict[str, Any]:
        return {
            "plugin_id": self.plugin_id,
            "scope_kind": self.scope_kind,
            "scope_name": self.scope_name,
            "has_secret": True,
            "has_grace_secret": self._grace_active(),
            "created_at": self.created_at.isoformat(),
            "rotated_at": self.rotated_at.isoformat() if self.rotated_at else None,
        }

    def to_storage_dict(self) -> dict[str, Any]:
        return {
            "plugin_id": self.plugin_id,
            "scope_kind": self.scope_kind,
            "scope_name": self.scope_name,
            "active_secret_value": encrypt_secret_value(self.active_secret_value),
            "previous_secret_value": encrypt_secret_value(self.previous_secret_value),
            "grace_deadline": (
                self.grace_deadline.isoformat() if self.grace_deadline else None
            ),
            "created_at": self.created_at.isoformat(),
            "rotated_at": self.rotated_at.isoformat() if self.rotated_at else None,
        }

    @classmethod
    def from_storage_dict(cls, data: dict[str, Any]) -> PluginSecret:
        created_at_raw = data.get("created_at")
        created_at = (
            datetime.fromisoformat(created_at_raw)
            if isinstance(created_at_raw, str)
            else None
        )
        entry = cls(
            plugin_id=str(data["plugin_id"]),
            scope_kind=str(data["scope_kind"]),
            scope_name=str(data["scope_name"]),
            active_secret_value=str(
                decrypt_secret_value(str(data["active_secret_value"]))
            ),
            created_at=created_at,
        )
        previous_raw = data.get("previous_secret_value")
        if isinstance(previous_raw, str) and previous_raw:
            decrypted_previous = decrypt_secret_value(previous_raw)
            entry.previous_secret_value = decrypted_previous
            entry.previous_secret_hash = (
                _hash_secret(decrypted_previous) if decrypted_previous else None
            )
        grace_deadline_raw = data.get("grace_deadline")
        if isinstance(grace_deadline_raw, str) and grace_deadline_raw:
            entry.grace_deadline = datetime.fromisoformat(grace_deadline_raw)
        rotated_at_raw = data.get("rotated_at")
        if isinstance(rotated_at_raw, str) and rotated_at_raw:
            entry.rotated_at = datetime.fromisoformat(rotated_at_raw)
        return entry


class SecretManager:
    """Persistent store of per-endpoint secrets."""

    def __init__(
        self,
        storage_path: Path | None = None,
        *,
        repository: PluginRepository | None = None,
    ) -> None:
        self._secrets: dict[str, PluginSecret] = {}
        self._storage_path = storage_path
        self._repository = repository
        self._load()

    @staticmethod
    def _key(plugin_id: str, scope_kind: str, scope_name: str) -> str:
        return f"{plugin_id}:{scope_kind}:{scope_name}"

    def _load(self, plugin_id: str | None = None) -> None:
        if self._repository is not None:
            raw: Any = {
                "secrets": self._repository.list_secret_payloads(plugin_id)
            }
        else:
            if self._storage_path is None or not self._storage_path.exists():
                return
            try:
                raw = json.loads(self._storage_path.read_text(encoding="utf-8"))
            except Exception as exc:  # noqa: BLE001
                logger.warning(
                    "Failed to load plugin secrets from %s: %s",
                    self._storage_path,
                    exc,
                )
                return
        if not isinstance(raw, dict):
            return
        loaded: dict[str, PluginSecret] = {}
        needs_encryption_migration = False
        for item in raw.get("secrets", []):
            if not isinstance(item, dict):
                continue
            try:
                entry = PluginSecret.from_storage_dict(item)
            except Exception as exc:  # noqa: BLE001
                logger.warning("Skipping invalid secret entry: %s", exc)
                continue
            active_stored = item.get("active_secret_value")
            previous_stored = item.get("previous_secret_value")
            needs_encryption_migration = needs_encryption_migration or (
                isinstance(active_stored, str)
                and bool(active_stored)
                and not is_encrypted_secret(active_stored)
            ) or (
                isinstance(previous_stored, str)
                and bool(previous_stored)
                and not is_encrypted_secret(previous_stored)
            )
            loaded[self._key(entry.plugin_id, entry.scope_kind, entry.scope_name)] = entry
        if self._repository is not None and plugin_id is not None:
            self._secrets = {
                key: entry
                for key, entry in self._secrets.items()
                if entry.plugin_id != plugin_id
            }
            self._secrets.update(loaded)
        else:
            self._secrets = loaded
        if needs_encryption_migration:
            self._save(loaded.values())

    def _save(self, entries: Iterable[PluginSecret] | None = None) -> None:
        if self._repository is not None:
            for entry in entries if entries is not None else self._secrets.values():
                self._repository.upsert_secret_payload(entry.to_storage_dict())
            return
        if self._storage_path is None:
            return
        self._storage_path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "secrets": [entry.to_storage_dict() for entry in self._secrets.values()],
        }
        tmp_path = self._storage_path.with_suffix(self._storage_path.suffix + ".tmp")
        tmp_path.write_text(
            json.dumps(payload, sort_keys=True, separators=(",", ":")),
            encoding="utf-8",
        )
        os.chmod(tmp_path, 0o600)
        os.replace(tmp_path, self._storage_path)

    def create_secret(
        self,
        plugin_id: str,
        scope_kind: str,
        scope_name: str,
    ) -> str:
        """Generate and store a new secret. Returns the raw value once."""
        if self._repository is not None:
            self._load(plugin_id)
        raw = _generate_secret()
        key = self._key(plugin_id, scope_kind, scope_name)
        self._secrets[key] = PluginSecret(
            plugin_id, scope_kind, scope_name, raw
        )
        self._save([self._secrets[key]])
        logger.info(
            "Created secret for %s/%s/%s", plugin_id, scope_kind, scope_name
        )
        return raw

    def ensure_secret(
        self,
        plugin_id: str,
        scope_kind: str,
        scope_name: str,
        *,
        initial_value: str | None = None,
    ) -> None:
        """Initialize a scope without rotating a value created by another worker."""
        key = self._key(plugin_id, scope_kind, scope_name)
        if self._repository is None:
            if key in self._secrets:
                return
            if initial_value is None:
                self.create_secret(plugin_id, scope_kind, scope_name)
            else:
                self.set_secret(plugin_id, scope_kind, scope_name, initial_value)
            return

        raw = initial_value.strip() if initial_value is not None else _generate_secret()
        if not raw:
            raise ValueError("initial_value must not be empty")
        candidate = PluginSecret(plugin_id, scope_kind, scope_name, raw)
        authoritative = self._repository.insert_secret_payload_if_absent(
            candidate.to_storage_dict()
        )
        self._secrets[key] = PluginSecret.from_storage_dict(authoritative)

    def rotate_secret(
        self,
        plugin_id: str,
        scope_kind: str,
        scope_name: str,
        *,
        grace_period: timedelta = DEFAULT_GRACE_PERIOD,
    ) -> str:
        """Rotate a secret. Returns the new raw value once."""
        if self._repository is not None:
            self._load(plugin_id)
        key = self._key(plugin_id, scope_kind, scope_name)
        existing = self._secrets.get(key)
        if existing is None:
            raise KeyError(f"No secret for {key!r}")

        new_raw = _generate_secret()
        existing.previous_secret_value = existing.active_secret_value
        existing.previous_secret_hash = existing.active_secret_hash
        existing.active_secret_value = new_raw
        existing.active_secret_hash = _hash_secret(new_raw)
        existing.grace_deadline = datetime.now(UTC) + grace_period
        existing.rotated_at = datetime.now(UTC)
        self._save([existing])

        logger.info(
            "Rotated secret for %s/%s/%s (grace=%s)",
            plugin_id,
            scope_kind,
            scope_name,
            grace_period,
        )
        return new_raw

    def set_secret(
        self,
        plugin_id: str,
        scope_kind: str,
        scope_name: str,
        raw_secret: str,
    ) -> None:
        """Import or replace a secret with an operator-supplied value."""
        if self._repository is not None:
            self._load(plugin_id)
        normalized = raw_secret.strip()
        if not normalized:
            raise ValueError("raw_secret must not be empty")

        key = self._key(plugin_id, scope_kind, scope_name)
        existing = self._secrets.get(key)
        now = datetime.now(UTC)

        if existing is None:
            self._secrets[key] = PluginSecret(
                plugin_id,
                scope_kind,
                scope_name,
                normalized,
                created_at=now,
            )
        else:
            existing.active_secret_value = normalized
            existing.active_secret_hash = _hash_secret(normalized)
            existing.previous_secret_value = None
            existing.previous_secret_hash = None
            existing.grace_deadline = None
            existing.rotated_at = now

        self._save([self._secrets[key]])
        logger.info(
            "Imported secret for %s/%s/%s",
            plugin_id,
            scope_kind,
            scope_name,
        )

    def verify(
        self,
        plugin_id: str,
        scope_kind: str,
        scope_name: str,
        raw_candidate: str,
    ) -> bool:
        if self._repository is not None:
            self._load(plugin_id)
        key = self._key(plugin_id, scope_kind, scope_name)
        entry = self._secrets.get(key)
        if entry is None:
            return False
        return entry.verify(raw_candidate)

    def verify_signature(
        self,
        plugin_id: str,
        scope_kind: str,
        scope_name: str,
        payload: bytes,
        signature: str,
    ) -> bool:
        entry = self.get_entry(plugin_id, scope_kind, scope_name)
        if entry is None:
            return False
        return entry.verify_signature(payload, signature)

    def get_entry(
        self, plugin_id: str, scope_kind: str, scope_name: str
    ) -> PluginSecret | None:
        if self._repository is not None:
            self._load(plugin_id)
        return self._secrets.get(self._key(plugin_id, scope_kind, scope_name))

    def get_raw_secret(
        self, plugin_id: str, scope_kind: str, scope_name: str
    ) -> str | None:
        entry = self.get_entry(plugin_id, scope_kind, scope_name)
        if entry is None:
            return None
        return entry.active_secret_value

    def list_for_plugin(self, plugin_id: str) -> list[PluginSecret]:
        if self._repository is not None:
            self._load(plugin_id)
        return [s for s in self._secrets.values() if s.plugin_id == plugin_id]

    def delete_for_plugin(self, plugin_id: str) -> int:
        if self._repository is not None:
            removed = self._repository.delete_plugin_secrets(plugin_id)
            self._load(plugin_id)
            return removed
        to_remove = [k for k, v in self._secrets.items() if v.plugin_id == plugin_id]
        for k in to_remove:
            del self._secrets[k]
        if to_remove:
            self._save()
        return len(to_remove)

    def sign_payload(
        self,
        plugin_id: str,
        scope_kind: str,
        scope_name: str,
        payload: bytes,
    ) -> str | None:
        entry = self.get_entry(plugin_id, scope_kind, scope_name)
        if entry is None:
            return None
        return entry.sign_payload(payload)
